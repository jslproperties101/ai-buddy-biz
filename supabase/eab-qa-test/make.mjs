// Batch 2b (9 Nov 2026, Joe's decision D-7N-2): AI Buddy Biz moves into the EAB-QA-Test Supabase project, in its own
// database area (schema "biz"), so it does not mix with Estate Agent AI Buddy's tables in "public".
//
// This script turns supabase/migrations/0001 ... 0011 (written for a project of its own, schema "public") into ONE file
// for the biz schema. The original files are not changed: they still build a stand-alone Biz project.
//   node supabase/eab-qa-test/make.mjs            -> writes supabase/eab-qa-test/20261109120000_biz_schema.sql
//   node supabase/eab-qa-test/make.mjs --check    -> exits 1 if that file is out of date
// What changes, and only this:
//   * every "public." becomes "biz." — names and the "public.%I" inside format() strings (every named object is created by
//     these migrations; checked below)
//   * every "search_path = public" becomes "search_path = biz, public" (so names without a schema find biz first)
//   * a header creates the schema and gives it the same default rights Supabase gives "public"
//   * the kids photo rules on storage.objects read folder names with biz.try_uuid(...) instead of "::uuid": EAB-QA-Test
//     shares storage.objects with Estate Agent AI Buddy, whose folder names are not ids, and PostgreSQL does not promise
//     to check "bucket_id = 'kids'" first, so a plain cast could make EAB's own file reads fail
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const migDir = join(here, '..', 'migrations');
const OUT = join(here, '20261109120000_biz_schema.sql');

const files = readdirSync(migDir).filter(f => /^\d{4}_.+\.sql$/.test(f)).sort();
if (files.length === 0) throw new Error('no migrations found');

const defined = new Set(), used = new Set();
const parts = files.map(f => {
  const src = readFileSync(join(migDir, f), 'utf8');
  for (const m of src.matchAll(/create\s+(?:or\s+replace\s+)?(?:table|function|view|type|sequence|materialized\s+view)\s+(?:if\s+not\s+exists\s+)?public\.([a-z_0-9]+)/gi)) defined.add(m[1]);
  for (const m of src.matchAll(/\bpublic\.([a-z_0-9]+)/gi)) used.add(m[1]);
  if (/\bschema\s+public\b|'public'|"public"/i.test(src)) throw new Error(`${f} names the public schema in a way this script does not convert`);
  const out = src
    .replace(/\bpublic\./gi, 'biz.')   // also inside format('... public.%I ...') used to build tables in a loop
    .replace(/search_path\s*=\s*public\b/gi, 'search_path = biz, public')
    .replace(/\(storage\.foldername\(name\)\)\[(\d)\]::uuid/g, 'biz.try_uuid((storage.foldername(name))[$1])');
  return `-- =====================================================================================================================\n-- ${f} (converted to schema biz)\n-- =====================================================================================================================\n${out}\n`;
});
if (/storage\.foldername\(name\)\)\[\d\]::uuid/.test(parts.join(''))) throw new Error('a storage folder cast was not converted');
const missing = [...used].filter(n => !defined.has(n));
if (missing.length) throw new Error(`these public.* names are not created by the Biz migrations: ${missing.join(', ')}`);

const header = `-- AI Buddy Biz database in the EAB-QA-Test project, schema "biz" (Batch 2b, 9 Nov 2026).
-- GENERATED by supabase/eab-qa-test/make.mjs from supabase/migrations/${files[0]} ... ${files.at(-1)} — do not edit by hand.
-- TEST project only (EAB-QA-Test, talksazsqsgjriamwxdp). Never production without Joe's yes.
-- After applying: Supabase Dashboard -> Project Settings -> Data API -> Exposed schemas: add "biz" (the app asks for it).
-- All or nothing: one transaction. Pasting it a second time stops at the first line and changes nothing.
begin;
do $guard$ begin
  if to_regclass('biz.tenants') is not null then
    raise exception 'AI Buddy Biz is already installed in schema biz; nothing was changed';
  end if;
end $guard$;
create schema if not exists biz;
-- names written without a schema (inside policies, loops and functions without their own search_path) resolve to biz first
set search_path = biz, public, extensions;
grant usage on schema biz to anon, authenticated, service_role;
-- the same default rights Supabase gives the public schema; Row Level Security on every table still decides who sees what,
-- and the migrations below revoke function rights where they mean to
alter default privileges in schema biz grant all on tables to anon, authenticated, service_role;
alter default privileges in schema biz grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema biz grant all on functions to anon, authenticated, service_role;
-- text -> uuid, or null when the text is not an id (used by the kids photo rules on the shared storage.objects)
create or replace function biz.try_uuid(t text) returns uuid language sql immutable set search_path = pg_catalog as $f$
  select case when t ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then t::uuid end $f$;

`;
const footer = `
commit;
select 'AI Buddy Biz installed in schema biz: ' || (select count(*) from pg_tables where schemaname = 'biz') || ' tables' as result;
`;
const text = header + parts.join('\n') + footer;
if (process.argv.includes('--check')) {
  const now = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
  if (now !== text) { console.error(`${OUT} is out of date: run node supabase/eab-qa-test/make.mjs`); process.exit(1); }
  console.log('up to date');
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}: ${files.length} migrations, ${defined.size} objects, ${text.length} characters`);
}
